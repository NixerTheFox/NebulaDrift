    /// Columns of a single glyph (0 = space ... 94 = "~", 95 = the note), one bit per row (bit 0 is the top row).
    static func glyphColumns(_ glyph: Int) -> [UInt8] {
        var out = [UInt8](repeating: 0, count: 5)
        for r in 0..<rows {
            let bits = font[glyph * rows + r]
            for x in 0..<5 where bits & (0x10 >> x) != 0 { out[x] |= 1 << r }
        }
        return out
    }

    /// The message as dot columns, with a blank column after each character. Other scripts are spelled in Latin
    /// letters and accents dropped (é → e); characters the font still doesn't have show as "?".
    static func columns(_ text: String) -> [UInt8] {
        var out: [UInt8] = []
        for g in glyphs(text) {
            out += glyphColumns(g)
            out.append(0)
        }
        return out
    }

    private static func glyphs(_ text: String) -> [Int] {
        var out: [Int] = []
        for ch in text {
            if ch == "♪" || ch == "♫" {
                out.append(note)
                continue
            }
            let replacements: [Character: String] = ["‘": "'", "’": "'", "“": "\"", "”": "\"", "–": "-", "—": "-",
                                                      "…": "...", "•": "*", "·": "*", "«": "\"", "»": "\""]
            var s = replacements[ch] ?? String(ch)
            if !s.allSatisfy(\.isASCII) {
                s = s.applyingTransform(.toLatin, reverse: false)?.applyingTransform(.stripDiacritics, reverse: false) ?? s
            }
            for scalar in s.unicodeScalars {
                let v = Int(scalar.value)
                if v < 32 { out.append(0) } else if v < 127 { out.append(v - 32) } else { out.append(Int(("?" as UnicodeScalar).value) - 32) }
            }
        }
        return out
    }
