/// Glyph indices for the characters of `utf8`.
static std::vector<int> glyphs(const std::string& utf8) {
    std::vector<int> out;
    auto ascii = [&](char ch) { out.push_back(ch >= 32 && ch < 127 ? ch - 32 : '?' - 32); };
    for (size_t i = 0; i < utf8.size();) {
        unsigned char b = utf8[i];
        uint32_t cp;
        int len;
        if (b < 0x80) cp = b, len = 1;
        else if ((b & 0xE0) == 0xC0) cp = b & 0x1F, len = 2;
        else if ((b & 0xF0) == 0xE0) cp = b & 0x0F, len = 3;
        else if ((b & 0xF8) == 0xF0) cp = b & 0x07, len = 4;
        else cp = '?', len = 1;
        for (int k = 1; k < len; k++) {
            if (i + k >= utf8.size() || (utf8[i + k] & 0xC0) != 0x80) {
                cp = '?';
                len = k;
                break;
            }
            cp = (cp << 6) | (utf8[i + k] & 0x3F);
        }
        i += len;
        if (cp < 0x80) ascii(cp < 32 ? ' ' : char(cp));
        else if (cp >= 0xC0 && cp <= 0xFF) ascii(latin1[cp - 0xC0]);
        else if (cp >= 0x100 && cp <= 0x17F) ascii(latinExtA[cp - 0x100]);
        else if (cp == 0xA0 || cp == 0x2002 || cp == 0x2003 || cp == 0x2009) ascii(' ');
        else if (cp == 0x2018 || cp == 0x2019 || cp == 0xB4) ascii('\'');
        else if (cp == 0x201C || cp == 0x201D || cp == 0xAB || cp == 0xBB) ascii('"');
        else if (cp == 0x2010 || cp == 0x2013 || cp == 0x2014 || cp == 0x2212) ascii('-');
        else if (cp == 0x2026) out.insert(out.end(), 3, '.' - 32);
        else if (cp == 0xB7 || cp == 0x2022) ascii('*');
        else if (cp == 0x266A || cp == 0x266B) out.push_back(note);
        else if (cp >= 0x300 && cp <= 0x36F) continue; // combining accents
        else ascii('?');
    }
    return out;
}

std::vector<uint8_t> glyphColumns(int glyph) {
    std::vector<uint8_t> out(5, 0);
    for (int r = 0; r < rows; r++) {
        uint8_t bits = font[glyph * rows + r];
        for (int x = 0; x < 5; x++) {
            if (bits & (0x10 >> x)) out[x] |= uint8_t(1 << r);
        }
    }
    return out;
}

std::vector<uint8_t> columns(const std::string& utf8) {
    std::vector<uint8_t> out;
    for (int g : glyphs(utf8)) {
        std::vector<uint8_t> cols = glyphColumns(g);
        out.insert(out.end(), cols.begin(), cols.end());
        out.push_back(0);
    }
    return out;
}

